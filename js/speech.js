const SYMBOLS = [
  ['ħ', 'аш с чертой'], ['ψ', 'пси'], ['ν', 'ню'], ['λ', 'лямбда'], ['φ', 'фи'], ['θ', 'тэта'], ['π', 'пи'],
  ['κ', 'каппа'], ['Δ', 'дельта'], ['α', 'альфа'], ['β', 'бета'], ['√', 'корень из '], ['≈', 'примерно'],
  ['≥', 'не меньше'], ['±', 'плюс-минус'], ['·', ' '], ['→', ', затем'], ['~', 'около '], ['%', ' процентов'],
  ['−', 'минус '], ['⟩', ''], ['|', ''], ['«', ''], ['»', ''], ['(', ', '], [')', ','], ['₂', ''], ['₁', ''], ['ᴺ', '']
];

export function spoken(text) {
  let s = text;
  for (const [re, w] of FORMULAS) s = s.replace(re, w);
  s = s.replace(/(Протон|Нейтрон) = /g, '$1 состоит из ').replace(/\s\(\d+\)\./g, '.').replace(/в ~(\d+)/g, 'примерно в $1').replace(/заряд \+1/g, 'заряд плюс один')
    .replace(/с l = 1/g, 'с орбитальным числом, равным единице').replace(/\s=\s/g, ' равно ');
  s = s.replace(/π-мезон/g, 'пи-мезон').replace(/π-/g, 'пи-');
  s = s.replace(/(\d+)\s*мК(?![а-яё])/gi, '$1 милликельвинов').replace(/(\d+)\s*K(?![a-z])/g, '$1 кельвинов')
    .replace(/(\d+)–(\d+)\s*ГГц/g, 'от $1 до $2 гигагерц').replace(/(\d+)\s*МэВ/g, '$1 мегаэлектронвольт')
    .replace(/(\d+(?:,\d+)?)\s*фм(?![а-яё])/g, '$1 фемтометра').replace(/1,4 фемтометра/g, 'одна и четыре десятых фемтометра');
  for (const [a, b] of SYMBOLS) s = s.split(a).join(b);
  return s.replace(/\s+([,.;:!?])/g, '$1').replace(/,(\s*,)+/g, ',').replace(/,(?=[^\s\d])/g, ', ').replace(/,\s*([.;:!?])/g, '$1').replace(/\s{2,}/g, ' ').trim();
}

// Ключ аудиофайла: короткий хеш произносимого текста (FNV-1a, 32 бита).
export function clipKey(text) {
  const s = spoken(text);
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 0x01000193) >>> 0; }
  return h.toString(16).padStart(8, '0');
}
